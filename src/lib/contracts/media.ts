/**
 * Client-safe image asset contract.
 *
 * The administrator uploads an original poster or banner; the server stores it
 * unchanged on the application-server disk and returns a stable `/media/...`
 * path. Nothing here performs image processing, so both the browser and the
 * server can share the same path and size rules.
 */

import { z } from 'zod';

/** The two independent image roles. A poster is never reused as a banner. */
export const IMAGE_KINDS = ['poster', 'banner'] as const;

export type ImageKind = (typeof IMAGE_KINDS)[number];

/** Content types that own poster and banner artwork. */
export const IMAGE_CONTENT_TYPES = ['drama', 'movie'] as const;

export type ImageContentType = (typeof IMAGE_CONTENT_TYPES)[number];

/** Maximum accepted original file size (5 MB). */
export const MAX_IMAGE_BYTES = 5 * 1024 * 1024;

/** Minimum accepted image dimensions. */
export const MIN_IMAGE_DIMENSION = 100;

/** Maximum accepted image dimensions. */
export const MAX_IMAGE_DIMENSION = 4000;

/** Allowed image formats, keyed by their canonical extension. */
export const ALLOWED_IMAGE_TYPES = [
  { mimeType: 'image/jpeg', extension: 'jpg', label: 'JPEG' },
  { mimeType: 'image/png', extension: 'png', label: 'PNG' },
  { mimeType: 'image/webp', extension: 'webp', label: 'WebP' },
  { mimeType: 'image/gif', extension: 'gif', label: 'GIF' },
] as const;

export type AllowedImageMimeType = (typeof ALLOWED_IMAGE_TYPES)[number]['mimeType'];

/** Human-readable `accept` attribute for the file picker. */
export const IMAGE_ACCEPT_ATTRIBUTE = ALLOWED_IMAGE_TYPES.map(type => type.mimeType).join(',');

/**
 * Managed image path: `/media/{kind}/{uuid}.{ext}`.
 *
 * The filename is generated by the server. A caller can never choose a path,
 * a directory, or an extension that the server did not create.
 */
export const MANAGED_IMAGE_PATH_PATTERN =
  /^\/media\/(poster|banner)\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(?:jpg|jpeg|png|webp|gif)$/;

/** Filename part of a managed path, used by the delivery route. */
export const MANAGED_IMAGE_FILENAME_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(?:jpg|jpeg|png|webp|gif)$/;

export function isManagedImagePath(value: string): boolean {
  return MANAGED_IMAGE_PATH_PATTERN.test(value);
}

/** Absolute HTTPS artwork URL supplied by an operator (legacy/imported rows). */
export const externalImageUrlSchema = z
  .url({ protocol: /^https?$/ })
  .max(2048)
  .refine(value => {
    // The refinement must never throw: a malformed value has to become a
    // validation error, not an unhandled `TypeError` from inside the schema.
    // Zod runs refinements even after the URL format check has failed, so the
    // parse is repeated defensively here.
    try {
      const url = new URL(value);
      return url.username === '' && url.password === '';
    } catch {
      return false;
    }
  }, 'Image URLs must not contain embedded credentials.');

/**
 * A stored image reference: either a managed `/media/...` path or an absolute
 * HTTP(S) URL. Relative paths outside `/media` and `file:` URLs are rejected.
 */
export const imageReferenceSchema = z.union([
  z.string().regex(MANAGED_IMAGE_PATH_PATTERN, 'Image must be an uploaded /media path.'),
  externalImageUrlSchema,
]);

export type ImageReference = z.infer<typeof imageReferenceSchema>;

/** Public URL path for one stored image. */
export function mediaPath(kind: ImageKind, filename: string): string {
  return `/media/${kind}/${filename}`;
}

/** The canonical extension for an accepted MIME type, or null. */
export function imageExtensionForMime(mimeType: string): string | null {
  return ALLOWED_IMAGE_TYPES.find(type => type.mimeType === mimeType)?.extension ?? null;
}

/** The content type served for a stored filename, or null when unsupported. */
export function imageContentTypeForFilename(filename: string): string | null {
  const extension = filename.slice(filename.lastIndexOf('.') + 1).toLowerCase();

  switch (extension) {
    case 'jpg':
    case 'jpeg':
      return 'image/jpeg';
    case 'png':
      return 'image/png';
    case 'webp':
      return 'image/webp';
    case 'gif':
      return 'image/gif';
    default:
      return null;
  }
}
