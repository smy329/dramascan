/**
 * systemd application management module.
 *
 * Provides Next.js application systemd service configuration including application
 * user, working directory, environment, restart behavior, startup dependencies,
 * and safe service limits. All maintenance commands are short-lived - no persistent
 * background workers or job queue monitoring.
 *
 * Do not implement: worker concurrency, dashboards, or persistent process monitoring.
 */

import 'server-only';

import { getDeploymentConfiguration } from './deployment.config';

/** systemd service state. */
export type SystemdServiceState = 'activating' | 'active' | 'deactivating' | 'inactive' | 'failed';

 /** systemd service unit file content. */
export interface SystemdServiceConfig {
  /** Service description */
  description: string;
  /** ExecStart command */
  execStart: string;
  /** ExecStop command */
  execStop: string;
  /** ExecRestart command */
  execRestart: string;
  /** Working directory */
  workingDirectory: string;
  /** User to run as */
  user: string;
  /** Environment variables */
  environment: Record<string, string>;
  /** Restart behavior */
  restart: 'no' | 'on-failure' | 'always' | 'on-abort' | 'on-watchdog';
  /** Start limit interval */
  startLimitIntervalSec: string;
  /** Start limit count */
  startLimitCount: number;
  /** Timeout stopSec */
  stopGracearySec: string;
  /** Timeout for start */
  startTimeoutSec: string;
  /** Timeout for stop */
  stopTimeoutSec: string;
  /** Logging */
  standardOutput: string;
  standardError: string;
}

/** Get default systemd service configuration. */
